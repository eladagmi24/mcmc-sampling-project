# Helper: set bidi on a paragraph element
def set_bidi(paragraph):
    pPr = paragraph._element.get_or_add_pPr()
    bidi = pPr.makeelement(qn('w:bidi'), {})
    pPr.append(bidi)


# Helper: set RTL on a run element
def set_run_rtl(run):
    rPr = run._element.get_or_add_rPr()
    rtl = rPr.makeelement(qn('w:rtl'), {})
    rPr.append(rtl)


# Helper functions
def add_slide_header(doc, slide_num, title_heb, title_eng):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    set_bidi(p)
    run = p.add_run('\u2014' * 50)
    run.font.color.rgb = RGBColor(0x00, 0x96, 0xD6)
    run.font.size = Pt(10)

    h = doc.add_heading(level=2)
    h.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    set_bidi(h)
    run = h.add_run('\u05e9\u05e7\u05e3 %d: %s (%s)' % (slide_num, title_heb, title_eng))
    run.font.name = 'David'
    run.font.size = Pt(16)
    run.font.color.rgb = RGBColor(0x00, 0x52, 0x8A)
    set_run_rtl(run)


def add_rtl_paragraph(doc, text, bold=False, size=13, color=None):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    set_bidi(p)
    run = p.add_run(text)
    run.font.name = 'David'
    run.font.size = Pt(size)
    run.font.bold = bold
    set_run_rtl(run)
    if color:
        run.font.color.rgb = color
    return p


